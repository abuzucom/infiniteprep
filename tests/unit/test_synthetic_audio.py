"""Behavioral tests for the seeded synthetic audio generator in tests/fixtures/synthetic_audio.py.

Each container test passes generated bytes through the app reader that handles that format.
The ADTS test walks the frame chain directly because the app has no ADTS reader yet.
"""

from __future__ import annotations

import json
import struct
from pathlib import Path

import numpy as np
import pytest
import soundfile as sf

from infiniteprep.adapters.metadata_io.metadata_tag_adapter import MetadataTagAdapter
from infiniteprep.adapters.metadata_io.mp4_reader import read_mp4
from infiniteprep.adapters.metadata_io.ogg_reader import read_ogg
from infiniteprep.domain.enums import AudioFormat
from tests.fixtures import synthetic_audio as sa

RATE = 44100
OGG_HEADER_SIZE = 27
OGG_CRC_SLICE = slice(22, 26)
ADTS_HEADER_SIZE = 7


def _frequency_bins(signal: np.ndarray, sample_rate: int) -> np.ndarray:
    """Return the rfft bin frequencies of signal. A sample rate below one raises ValueError."""
    if sample_rate <= 0:
        raise ValueError(f"sample_rate must be positive, got {sample_rate}. Pass the signal rate.")
    return np.fft.rfftfreq(len(signal), 1.0 / sample_rate)


def _spectrum_peaks(signal: np.ndarray, sample_rate: int, count: int) -> list[float]:
    """Return the count strongest frequencies of signal, in ascending order."""
    magnitudes = np.abs(np.fft.rfft(signal))
    freqs = _frequency_bins(signal, sample_rate)
    strongest = np.argsort(magnitudes)[-count:]
    return sorted(float(freqs[index]) for index in strongest)


def _band_energy_fraction(signal: np.ndarray, sample_rate: int, low: float, high: float) -> float:
    """Return the share of spectral energy between low and high hertz.

    A silent signal has no energy to share and raises ValueError.
    """
    power = np.abs(np.fft.rfft(signal)) ** 2
    freqs = _frequency_bins(signal, sample_rate)
    total = power.sum()
    if total <= 0:
        raise ValueError("The signal is silent. Generate a signal with energy before measuring it.")
    inside = power[(freqs >= low) & (freqs <= high)].sum()
    return float(inside / total)


def _ogg_crc(page: bytes) -> int:
    """Compute the Ogg page CRC bit by bit, independent of the generator's table."""
    crc = 0
    for byte in page:
        crc ^= byte << 24
        for _ in range(8):
            crc = ((crc << 1) ^ 0x04C11DB7) if crc & 0x80000000 else crc << 1
            crc &= 0xFFFFFFFF
    return crc


def _ogg_pages(data: bytes) -> list[bytes]:
    """Split Ogg bytes into pages using the segment tables."""
    pages: list[bytes] = []
    offset = 0
    while offset < len(data):
        assert data[offset : offset + 4] == b"OggS"
        segments = data[offset + 26]
        lacing = data[offset + OGG_HEADER_SIZE : offset + OGG_HEADER_SIZE + segments]
        end = offset + OGG_HEADER_SIZE + segments + sum(lacing)
        pages.append(data[offset:end])
        offset = end
    return pages


def _adts_frames(data: bytes) -> list[tuple[int, int, int]]:
    """Walk ADTS frames and return (sample rate index, channels, frame length) per frame."""
    frames: list[tuple[int, int, int]] = []
    offset = 0
    while offset < len(data):
        header = int.from_bytes(data[offset : offset + ADTS_HEADER_SIZE], "big")
        assert header >> 44 == 0xFFF, f"missing syncword at byte {offset}"
        assert (header >> 41) & 0x3 == 0, "layer must be 0"
        assert (header >> 40) & 0x1 == 1, "fixture frames carry no CRC"
        assert (header >> 38) & 0x3 == 1, "profile must be AAC LC"
        frame_length = (header >> 13) & 0x1FFF
        assert frame_length > ADTS_HEADER_SIZE
        frames.append(((header >> 34) & 0xF, (header >> 30) & 0x7, frame_length))
        offset += frame_length
    assert offset == len(data), "frame lengths must tile the file exactly"
    return frames


def test_click_onsets_follow_tempo_changes() -> None:
    """Beat times step at the base tempo, then at the new tempo after the change."""
    onsets = sa.compute_click_onsets(
        bpm=120.0, duration_sec=4.0, tempo_changes=(sa.TempoChange(at_sec=2.0, bpm=150.0),)
    )
    assert onsets[:5] == pytest.approx([0.0, 0.5, 1.0, 1.5, 2.0])
    assert np.diff(onsets[4:]) == pytest.approx([0.4] * (len(onsets) - 5))
    assert onsets[-1] < 4.0


def test_click_track_places_clicks_and_accents_downbeats() -> None:
    """Each onset starts a click, and downbeats peak louder than other beats."""
    signal = sa.synthesize_click_track(bpm=120.0, duration_sec=4.0, sample_rate=RATE)
    assert signal.dtype == np.float32
    assert signal.shape == (4 * RATE,)
    click_len = int(sa.CLICK_DURATION_SEC * RATE)
    peaks = [
        float(np.abs(signal[int(t * RATE) : int(t * RATE) + click_len]).max())
        for t in sa.compute_click_onsets(bpm=120.0, duration_sec=4.0)
    ]
    assert all(peak > 0.1 for peak in peaks)
    assert peaks[0] > peaks[1] * 1.5
    assert peaks[4] == pytest.approx(peaks[0])
    gap = signal[click_len + 10 : int(0.5 * RATE) - 10]
    assert np.abs(gap).max() == 0.0


def test_tone_and_chord_peak_at_requested_frequencies() -> None:
    """A tone peaks at its frequency and a chord peaks at each note."""
    tone = sa.synthesize_tone(440.0, duration_sec=1.0, sample_rate=RATE)
    assert _spectrum_peaks(tone, RATE, 1) == pytest.approx([440.0], abs=1.0)
    notes = (261.63, 329.63, 392.0)
    chord = sa.synthesize_chord(notes, duration_sec=1.0, sample_rate=RATE)
    assert _spectrum_peaks(chord, RATE, 3) == pytest.approx(list(notes), abs=1.0)
    assert np.abs(chord).max() <= 1.0


def test_noise_is_seeded() -> None:
    """The same seed repeats the noise and another seed changes it."""
    first = sa.synthesize_noise(duration_sec=0.5, sample_rate=RATE, seed=7)
    again = sa.synthesize_noise(duration_sec=0.5, sample_rate=RATE, seed=7)
    other = sa.synthesize_noise(duration_sec=0.5, sample_rate=RATE, seed=8)
    assert first.tobytes() == again.tobytes()
    assert first.tobytes() != other.tobytes()
    assert _band_energy_fraction(first, RATE, 10000.0, RATE / 2) > 0.4


def test_band_limited_noise_stays_in_band() -> None:
    """Band-limited noise keeps nearly all energy between its edges."""
    noise = sa.synthesize_band_limited_noise(
        low_hz=200.0, high_hz=2000.0, duration_sec=1.0, sample_rate=RATE, seed=3
    )
    assert _band_energy_fraction(noise, RATE, 200.0, 2000.0) > 0.999


def test_lowpass_shelf_removes_content_above_cutoff() -> None:
    """The MP3-like shelf drops energy above the cutoff by the requested depth."""
    noise = sa.synthesize_noise(duration_sec=1.0, sample_rate=RATE, seed=5)
    shelved = sa.apply_lowpass_shelf(noise, sample_rate=RATE, cutoff_hz=16000.0)
    before = _band_energy_fraction(noise, RATE, 16500.0, RATE / 2)
    after = _band_energy_fraction(shelved, RATE, 16500.0, RATE / 2)
    assert before > 0.2
    assert after < before * 1e-5
    assert _band_energy_fraction(shelved, RATE, 0.0, 16000.0) > 0.99


def test_wav_fixture_reads_back_and_repeats(tmp_path: Path) -> None:
    """A written WAV passes the app reader and repeats byte for byte for one seed."""
    signal = sa.synthesize_noise(duration_sec=1.0, sample_rate=RATE, seed=11)
    first = sa.write_wav_fixture(tmp_path / "a.wav", signal, sample_rate=RATE)
    second = sa.write_wav_fixture(tmp_path / "b.wav", signal, sample_rate=RATE)
    assert first.read_bytes() == second.read_bytes()
    meta = MetadataTagAdapter().read_metadata(first)
    assert meta.format == AudioFormat.WAV
    assert meta.sample_rate == RATE
    assert meta.channels == 1
    assert meta.duration == pytest.approx(1.0)
    decoded, rate = sf.read(str(first), dtype="float32")
    assert rate == RATE
    assert np.abs(decoded - signal).max() < 1e-4


def test_adts_frames_tile_the_file() -> None:
    """ADTS frames carry the AAC LC header and tile the file without gaps."""
    data = sa.build_adts_bytes(frame_count=12, sample_rate=48000, channels=2, seed=1)
    frames = _adts_frames(data)
    assert len(frames) == 12
    assert {(index, channels) for index, channels, _ in frames} == {(3, 2)}
    assert data == sa.build_adts_bytes(frame_count=12, sample_rate=48000, channels=2, seed=1)
    assert data != sa.build_adts_bytes(frame_count=12, sample_rate=48000, channels=2, seed=2)


def test_adts_rejects_unlisted_sample_rate() -> None:
    """ADTS headers hold a rate index, so an unlisted rate raises ValueError."""
    with pytest.raises(ValueError, match="sample rate"):
        sa.build_adts_bytes(sample_rate=12345)


@pytest.mark.parametrize(
    ("builder", "codec", "bit_depth"),
    [(sa.build_m4a_aac_bytes, "mp4a", 16), (sa.build_m4a_alac_bytes, "alac", 24)],
)
def test_m4a_fixtures_pass_mp4_reader(tmp_path: Path, builder, codec: str, bit_depth: int) -> None:
    """AAC and ALAC M4A fixtures pass the MP4 reader and the tag adapter."""
    options = {"duration_sec": 2.0, "sample_rate": RATE, "channels": 2, "bit_depth": bit_depth}
    data = builder(**options, seed=4)
    info = read_mp4(data)
    assert info.codec == codec
    assert info.sample_rate == RATE
    assert info.channels == 2
    assert info.bit_depth == bit_depth
    assert info.duration == pytest.approx(2.0)
    assert info.bitrate
    path = tmp_path / "fixture.m4a"
    path.write_bytes(data)
    meta = MetadataTagAdapter().read_metadata(path)
    assert meta.format == AudioFormat.M4A
    assert meta.sample_rate == RATE
    assert not any("Damaged" in text for text in meta.warnings)
    assert data == builder(**options, seed=4)
    assert data != builder(**options, seed=9)


def test_stem_fixture_holds_mixdown_stems_and_manifest(tmp_path: Path) -> None:
    """A STEM.MP4 fixture holds five sound tracks and a stem manifest the readers accept."""
    data = sa.build_stem_mp4_bytes(duration_sec=1.0, sample_rate=RATE, seed=2)
    info = read_mp4(data)
    assert info.codec == "mp4a"
    assert info.duration == pytest.approx(1.0)
    assert data.count(b"trak") == 5
    assert data.count(b"soun") == 5
    manifest_at = data.index(b"stem") + 4
    manifest_size = struct.unpack(">I", data[manifest_at - 8 : manifest_at - 4])[0]
    manifest = json.loads(data[manifest_at : manifest_at - 8 + manifest_size])
    assert [stem["name"] for stem in manifest["stems"]] == list(sa.DEFAULT_STEM_NAMES)
    path = tmp_path / "fixture.stem.mp4"
    path.write_bytes(data)
    assert MetadataTagAdapter().read_metadata(path).sample_rate == RATE
    assert data == sa.build_stem_mp4_bytes(duration_sec=1.0, sample_rate=RATE, seed=2)


def test_ogg_vorbis_fixture_passes_ogg_reader(tmp_path: Path) -> None:
    """An Ogg Vorbis fixture has valid page CRCs and passes the Ogg reader and the adapter."""
    data = sa.build_ogg_vorbis_bytes(
        duration_sec=3.0, sample_rate=RATE, channels=2, seed=6, fields=(("TITLE", "Click"),)
    )
    for page in _ogg_pages(data):
        stored = struct.unpack("<I", page[OGG_CRC_SLICE])[0]
        assert stored == _ogg_crc(page[:22] + bytes(4) + page[26:])
    meta = read_ogg(data)
    assert meta.codec == "vorbis"
    assert meta.channels == 2
    assert meta.duration == pytest.approx(3.0, abs=0.03)
    assert ("TITLE", "Click") in meta.comment.fields
    path = tmp_path / "fixture.ogg"
    path.write_bytes(data)
    assert MetadataTagAdapter().read_metadata(path).sample_rate == RATE
    assert data == sa.build_ogg_vorbis_bytes(
        duration_sec=3.0, sample_rate=RATE, channels=2, seed=6, fields=(("TITLE", "Click"),)
    )


def test_ogg_opus_fixture_passes_ogg_reader() -> None:
    """An Ogg Opus fixture spans several pages, keeps valid CRCs, and passes the Ogg reader."""
    data = sa.build_ogg_opus_bytes(duration_sec=6.0, channels=1, seed=8)
    pages = _ogg_pages(data)
    assert len(pages) > 3
    assert pages[0][5] == 0x02
    assert pages[-1][5] & 0x04
    for page in pages:
        stored = struct.unpack("<I", page[OGG_CRC_SLICE])[0]
        assert stored == _ogg_crc(page[:22] + bytes(4) + page[26:])
    meta = read_ogg(data)
    assert meta.codec == "opus"
    assert meta.channels == 1
    assert meta.duration == pytest.approx(6.0)
    assert data == sa.build_ogg_opus_bytes(duration_sec=6.0, channels=1, seed=8)
    assert data != sa.build_ogg_opus_bytes(duration_sec=6.0, channels=1, seed=9)
